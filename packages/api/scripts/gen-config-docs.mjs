import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

// Render `docs/configuration.md` from the field table.
//
// The table in `src/config/schema.ts` drives validation and the environment
// mapping, so generating the reference from it means the documentation cannot
// describe a key the server ignores. `--check` fails when the file on disk is
// stale, which is what CI runs.

const OUTPUT = path.join(process.cwd(), '..', '..', 'docs', 'configuration.md');
const SCHEMA = path.join(process.cwd(), 'dist', 'config', 'schema.js');

// The table is consumed from the compiled module so this script and the server
// can never disagree. `pnpm run build` runs first in CI; running this alone on a
// clean tree builds it rather than failing with a confusing stack trace.
if (!fs.existsSync(SCHEMA)) {
  process.stderr.write('gen:config-docs: dist is missing, running pnpm run build first\n');
  execFileSync('pnpm', ['run', 'build'], { stdio: 'inherit' });
}

const { CONFIG_FIELDS } = await import(SCHEMA);

const escapeCell = (value) => String(value).replace(/\|/g, '\\|');

const render = () => {
  const rows = CONFIG_FIELDS.map((field) => {
    const type =
      field.kind === 'enum'
        ? `one of \`${field.values.join('`, `')}\``
        : field.kind === 'string-list'
          ? 'comma-separated list'
          : field.kind === 'string-map'
            ? '`name=path` pairs'
            : field.kind.replace('-', ' ');

    const fallback =
      field.defaultValue === undefined
        ? '—'
        : `\`${typeof field.defaultValue === 'string' ? field.defaultValue : JSON.stringify(field.defaultValue)}\``;

    const env = [`\`${field.env}\``, ...(field.legacyEnv ?? []).map((name) => `\`${name}\``)].join(
      ' / '
    );

    return `| \`${field.path}\` | ${escapeCell(type)} | ${escapeCell(field.summary)} | ${env} | ${fallback} |`;
  });

  return [
    '# Configuration',
    '',
    '<!-- Generated by `pnpm run gen:config-docs` from `src/config/schema.ts`. Do not edit. -->',
    '',
    'Precedence, lowest to highest:',
    '',
    '1. built-in defaults',
    '2. the config file (`HASTE_CONFIG`, `--config`, or `./config.js`)',
    '3. the environment',
    '',
    'Inside the environment layer, `<NAME>_FILE` beats `<NAME>`, and the canonical',
    '`HASTE_*` name beats a legacy alias. `<NAME>_FILE` is the Docker secret /',
    'Kubernetes mounted-secret convention: point it at a file and the value never',
    'enters the process environment.',
    '',
    '`HASTE_CONFIG=` (empty) skips the file layer entirely, for pure-environment',
    'deployments. Unknown keys in the file are preserved and ignored, so a newer',
    'file can be read by an older binary.',
    '',
    '## Envelope variables',
    '',
    '|variable|meaning|',
    '|---|---|',
    '|`HASTE_CONFIG`|Config file path. Empty disables the file layer.|',
    '|`HASTE_CONFIG_SOPS`|`1` forces SOPS decryption of the config file.|',
    '|`HASTE_CONFIG_NO_SOPS`|`1` disables SOPS detection (plain JSON only).|',
    '',
    '## Settings',
    '',
    '|key|type|meaning|environment|default|',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '## Secrets',
    '',
    'Keys below are masked (`***`) in the boot log and never printed by',
    '`GET /openapi.json`. Credentials embedded in a connection string are masked too,',
    'wherever they appear.',
    '',
    '|key|preferred delivery|',
    '|---|---|',
    ...CONFIG_FIELDS.filter((field) => field.secret).map(
      (field) => `| \`${field.path}\`|\`${field.env}_FILE\` (Docker/Kubernetes) or SOPS|`
    ),
    '',
    '## SOPS',
    '',
    'A config file is decrypted when it contains a top-level `sops` block, when its',
    'name ends in `.sops.`/`.yaml`/`.yml`, or when `HASTE_CONFIG_SOPS=1` is set.',
    'Decryption shells out to `sops --decrypt --output-type json`, so key material',
    '(age, PGP, KMS, Vault) stays owned by SOPS and never reaches this process.',
    '',
    '```sh',
    'sops --encrypt --age "$HASTE_AGE_RECIPIENT" config.json > config.sops.json',
    'HASTE_CONFIG=config.sops.json node dist/server.js',
    '```',
    '',
    'A missing `sops` binary is a boot failure with a fix in the message, never a',
    'silently empty config.',
    '',
    '## Validation',
    '',
    'Every problem is reported at once, with the layer that supplied the value:',
    '',
    '```',
    'invalid config: port: must be >= 1 (got 0)',
    'invalid config: storage.type: must be one of file, redis, … (got s3)',
    '```',
    '',
    'The first line keeps the `invalid config: <key>: <detail>` shape that log',
    'searches already match.',
    ''
  ].join('\n');
};

// Formatted with the repository's prettier config, so the generated file and
// `pnpm run format:check` can never disagree.
const expected = execFileSync('pnpm', ['exec', 'prettier', '--stdin-filepath', OUTPUT], {
  input: render(),
  encoding: 'utf8'
});

if (process.argv.includes('--check')) {
  const actual = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';

  if (actual !== expected) {
    process.stderr.write(
      'configuration docs are stale: run `npm run gen:config-docs` and commit docs/configuration.md\n'
    );
    process.exit(1);
  }

  process.stdout.write('check:config-docs: docs/configuration.md is current\n');
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, expected);
process.stdout.write(`gen:config-docs: wrote ${path.relative(process.cwd(), OUTPUT)}\n`);
